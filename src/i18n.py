def set_language(code: str) -> str:
    global _current_language
    requested = str(code or "").lower()
    if requested == SYSTEM_LANGUAGE:
        requested = system_language()
    _current_language = requested if requested in LANGUAGES else DEFAULT_LANGUAGE
    return _current_language


def t(key: str, **kwargs) -> str:
    text = _TRANSLATIONS.get(_current_language, {}).get(key)
    if text is None:
        text = _TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
    return text.format(**kwargs) if kwargs else text
