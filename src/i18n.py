def system_language() -> str:
    try:
        locale_name = locale.getlocale()[0] or ""
    except (ValueError, TypeError):
        locale_name = ""
    code = locale_name.replace("-", "_").split("_", 1)[0].lower()
    if code == "fil":
        code = "tl"
    return code if code in LANGUAGES else DEFAULT_LANGUAGE


